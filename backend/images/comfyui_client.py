# llm_description should be no longer than 60 words as stable 1.5 encoder only encode first 77 tokens
def truncate_words(text: str, max_words: int = 60) -> str:
    parts = text.split()
    if len(parts) <= max_words:
        return text
    return ' '.join(parts[:max_words])

def clean_llm_description(llm_description: str) -> str:
    """    
    Input:
        llm_description (str): The raw world description text generated by the LLM.    
    Output:
        clean_prompt (str): A cleaned prompt string for node 6.
    """
    if not llm_description or not llm_description.strip():
        raise ValueError("LLM description is empty.")
    
    # remove white spaces
    normalized = re.sub(r'\s+', ' ', llm_description.strip())

    return truncate_words(normalized, max_words=60)

def build_prompt_payload(clean_prompt: str) -> Dict[str, Any]:
    """
    Input:
        clean_prompt (str): The cleaned world description from clean_llm_description().
    Output:
        payload (dict): {"prompt": <workflow>}
    """
    workflow_copy = json.loads(json.dumps(EXPORTED_WORKFLOW))

    # chuck cleaned description to node 6
    node6 = workflow_copy.get("6")
    node6_inputs = node6.get("inputs", {})
    node6_inputs["text"] = clean_prompt

    prompt_payload = {"prompt": workflow_copy}
    return prompt_payload

def enqueue_render(prompt_payload: Dict[str, Any]) -> str:
    """
    Input:
        prompt_payload (dict): from build_prompt_payload()
    Output:
        prompt_id (str): returned by ComfyUI after sending a request
    """
    body = {'prompt': prompt_payload['prompt'], 'client_id': CLIENT_ID}
    response = requests.post(f'{COMFYUI_BASE_URL}/prompt', json = body)
    response.raise_for_status()
    data = response.json()
    prompt_id = data.get('prompt_id')
    if not prompt_id:
        raise RuntimeError(f'/prompt response missing prompt_id.')
    return prompt_id

def get_image_location(prompt_id: str, 
                       max_wait_s: float = 50.0, 
                       poll_every_s: float = 0.5) -> ImageLocation:
    
    history_url = f'{COMFYUI_BASE_URL}/history/{prompt_id}'
    deadline = time.time() + max_wait_s

    # continuously checking if image is generated
    while time.time() < deadline:
        response = requests.get(history_url)

        history_payload = response.json() or {}

        entry = history_payload.get(prompt_id) or {}
        outputs_by_node = entry.get('outputs') or {}

        for node_id, node_output in outputs_by_node.items():
            images = node_output.get('images') or []
            if images: # if image exists, return its data for later fetching from /view?...
                first_image = images[0]
                return ImageLocation(
                    filename=first_image.get('filename', ''),
                    subfolder=first_image.get('subfolder', ''),
                    type=first_image.get('type', 'output')
                )

        time.sleep(poll_every_s)

    raise TimeoutError('Timed out while waiting for image.')

def fetch_png_bytes(image_location: ImageLocation) -> bytes:
    """
    Input:
        image_location (ImageLocation): from get_image_location()
    Output:
        png_bytes (bytes): 
    """
    params = {
        'filename': image_location.filename,
        'subfolder': image_location.subfolder,
        'type': image_location.type
    }
    response = requests.get(f'{COMFYUI_BASE_URL}/view', params=params, stream=True)
    response.raise_for_status()
    return response.content

